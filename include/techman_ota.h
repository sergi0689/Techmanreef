class TmCertStore : public BearSSL::CertStoreBase {
  TmAnchor selected{};
  br_x509_trust_anchor anchor{};
  static const br_x509_trust_anchor *lookup(void *ctx, void *hash, size_t len) {
    if(len!=32 || !ctx || !hash)return nullptr;
    TmCertStore *self=static_cast<TmCertStore*>(ctx);
    for(size_t i=0;i<sizeof(tmAnchors)/sizeof(tmAnchors[0]);++i){
      if(memcmp_P(hash,tmAnchors[i].hash,32)!=0)continue;
      memcpy_P(&self->selected,&tmAnchors[i],sizeof(TmAnchor));
      auto &a=self->anchor; auto &s=self->selected;
      memset(&a,0,sizeof(a));
      a.dn.data=s.hash;a.dn.len=32;a.flags=BR_X509_TA_CA;
      a.pkey.key_type=s.type;
      if(s.type==BR_KEYTYPE_RSA){
        a.pkey.key.rsa.n=s.a;a.pkey.key.rsa.nlen=s.aLen;
        a.pkey.key.rsa.e=s.b;a.pkey.key.rsa.elen=s.bLen;
      }else{
        a.pkey.key.ec.curve=s.curve;a.pkey.key.ec.q=s.a;a.pkey.key.ec.qlen=s.aLen;
      }
      return &a;
    }
    return nullptr;
  }
  static void release(void *,const br_x509_trust_anchor *) {}
public:
  void installCertStore(br_x509_minimal_context *ctx) override {
    br_x509_minimal_set_dynamic(ctx,this,lookup,release);
  }
};
